package com.dahamdi.travelmanagement.service;

import com.dahamdi.travelmanagement.entity.Invoice;
import com.dahamdi.travelmanagement.entity.Payment;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * Payment gateway (admin side).
 *  - If an existing invoice is chosen, the payment is checked against its outstanding balance
 *    ON THE SERVER (the JavaScript check alone can be bypassed).
 *  - If no invoice is chosen, a new invoice with a guaranteed-unique number is created first.
 * Both steps run in one transaction, so a failed payment never leaves a half-created invoice.
 */
@Service
public class GatewayPaymentService {

    private final InvoiceService invoiceService;
    private final PaymentService paymentService;

    public GatewayPaymentService(InvoiceService invoiceService, PaymentService paymentService) {
        this.invoiceService = invoiceService;
        this.paymentService = paymentService;
    }

    public record GatewayResult(Invoice invoice, Payment payment, boolean autoGenerated) {
    }

    @Transactional
    public GatewayResult pay(Integer invoiceId, String customerName, BigDecimal amount, String paymentMethod) {

        if (amount == null || amount.signum() <= 0) {
            throw new IllegalArgumentException("Payment amount must be greater than 0.");
        }

        String method = (paymentMethod != null && !paymentMethod.isBlank()) ? paymentMethod : "CARD";
        boolean autoGenerated = false;
        Invoice invoice;

        if (invoiceId != null && invoiceId > 0) {
            // A selected invoice that doesn't exist is an error - don't silently create a new one.
            invoice = invoiceService.getInvoiceOrThrow(invoiceId);
        } else {
            String customer = (customerName != null && !customerName.isBlank())
                    ? customerName.trim() : "Gateway Customer";
            invoice = invoiceService.createInvoice(
                    invoiceService.generateInvoiceNumber(), customer, LocalDateTime.now(), amount);
            autoGenerated = true;
        }

        Payment payment = paymentService.createPayment(
                invoice.getInvoiceId(), LocalDateTime.now(), amount, method, PaymentService.STATUS_COMPLETED);

        return new GatewayResult(invoice, payment, autoGenerated);
    }
}
